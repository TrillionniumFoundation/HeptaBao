def added(before,peers):
    data=copy.deepcopy(before)
    bodies=''.join('### tuple ### allow tcp 31040:31041 192.168.0.11/32 any '+peer+'/32 in_br0 comment='+v.TAGS[peer].encode().hex()+'\n'+line(peer)+'\n\n' for peer in peers)
    data['etc-ufw-user.rules']=data['etc-ufw-user.rules'].replace(b'### END RULES ###',bodies.encode()+b'### END RULES ###')
    data['iptables-filter.original.private.log']=data['iptables-filter.original.private.log'].replace(b'COMMIT', ''.join('[0:0] '+line(peer)+'\n' for peer in peers).encode()+b'COMMIT')
    nft=json.loads(data['nft.original.private.log']); nft['nftables'] += [rule(peer,100+i) for i,peer in enumerate(peers)]
    data['nft.original.private.log']=json.dumps(nft).encode()
    return data


def mutate_nft(data,operation):
    nft=json.loads(data['nft.original.private.log']); operation(nft['nftables']); data['nft.original.private.log']=json.dumps(nft).encode()


