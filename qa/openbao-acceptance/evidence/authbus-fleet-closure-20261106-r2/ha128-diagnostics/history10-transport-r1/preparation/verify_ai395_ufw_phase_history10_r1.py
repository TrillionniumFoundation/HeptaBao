def validate_closed_capture(actual,name,root_identity):
    facts=actual['fdCloseFacts']; opened={'created':13,'input':19,'directory':3}
    need(actual['schema']=='heptabao.ai395-ufw-private-phase-capture.r1' and actual['ok'] is True
         and actual['privateBackupComplete'] is True and actual['phase']==name and actual['rootIdentity']==root_identity
         and facts['allOpenedFdsKnownClosed'] is True and facts['errorCount']==0 and facts['firstError'] is None
         and facts['opened']==facts['attemptedOnce']==facts['knownClosed']==opened,
         'actual_capture_stdout_fd_closure_required')


def main():
    held=[]; report={'schema':'heptabao.ai395-ufw-phase-semantic-verification.r1','ok':False,
                    'childCount':0,'networkPacketsSent':0,'firewallWrites':0,'originalFilesChanged':False}
    def timeout(signum,frame): raise RuntimeError('verification_deadline')
    signal.signal(signal.SIGALRM,timeout); signal.alarm(20)
    try:
        need(os.getuid()==0 and platform.node()=='ai395' and len(sys.argv)==2,'fixed_privileged_readonly_host')
        need(len(sys.argv[1].encode())<=32768,'bounded_verification_manifest')
        manifest=json.loads(sys.argv[1])
        need(set(manifest)=={'phase','rootIdentity','captureAuthorities'},'exact_verification_manifest')
        phase=manifest['phase']; need(phase in STATES,'fixed_phase'); root_identity=manifest['rootIdentity']
        need(set(manifest['captureAuthorities'])=={'before',phase},'original_capture_authorities_required')
        st=ROOT.lstat(); need(ROOT.resolve(strict=True)==ROOT and identity(st)[:5]==tuple(int(x) for x in root_identity)
                            and st.st_uid==0 and stat.S_IMODE(st.st_mode)==0o700,'original_private_root_identity')
        def read(path,maximum,owner=0):
            st=path.lstat(); need(path.resolve(strict=True)==path and stat.S_ISREG(st.st_mode) and st.st_uid==owner
                and stat.S_IMODE(st.st_mode)==0o600 and st.st_nlink==1 and st.st_size<=maximum,'private_regular_backup')
            fd=os.open(path,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK); held.append((path,fd,identity(st)))
            raw=bytearray()
            while True:
                part=os.read(fd,min(65536,st.st_size+1-len(raw)))
                if not part: break
                raw.extend(part); need(len(raw)<=st.st_size,'bounded_backup_growth')
            need(len(raw)==st.st_size and identity(os.fstat(fd))==identity(path.lstat())==identity(st),'stable_backup_bytes')
            return bytes(raw)
        authoritative_captures={}
        for name,authority in manifest['captureAuthorities'].items():
            validate_capture_authority(authority)
            raw=read(Path(authority['path']),65536,1000)
            need(len(raw)==authority['bytes'] and hashlib.sha256(raw).hexdigest()==authority['sha256'],
                 'original_capture_full_stdout_bytes')
            actual=json.loads(raw); validate_closed_capture(actual,name,root_identity)
            authoritative_captures[name]=actual
        def load(name):
            directory=ROOT/name; ds=directory.lstat()
            need(directory.resolve(strict=True)==directory and stat.S_ISDIR(ds.st_mode)
                 and ds.st_uid==0 and stat.S_IMODE(ds.st_mode)==0o700,'private_backup_phase')
            need(set(os.listdir(directory))==FILES|{'capture.public.json','nft.eof-authority.original.json',
                 'iptables-filter.eof-authority.original.json'},'exact_private_phase_membership')
            receipt=json.loads(read(directory/'capture.public.json',65536))
            need(receipt['ok'] is True and receipt['privateBackupComplete'] is True
                 and receipt['systemSourcePinsUnchanged'] is True and receipt['phase']==name
                 and receipt['rootIdentity']==root_identity and receipt['phaseIdentity']==[str(x) for x in identity(ds)[:5]]
                 and set(receipt['files'])==FILES,'complete_source_bound_phase')
            actual=authoritative_captures[name]
            need({k:v for k,v in actual.items() if k!='fdCloseFacts'}==receipt,
                 'private_receipt_bound_to_closed_original_capture_stdout')
            files={}
            for filename,pin in receipt['files'].items():
                data=read(directory/filename,2097152)
                need(len(data)==pin['bytes'] and hashlib.sha256(data).hexdigest()==pin['sha256'],'exact_phase_file_pin')
                files[filename]=data
            return receipt,files
        original,before=load('before'); current,after=load(phase)
        for name in FILES:
            if name.startswith('etc-'):
                need(original['files'][name]['originalIdentity'][:6]==current['files'][name]['originalIdentity'][:6],
                     'existing_config_custody_unchanged')
        result=compare(before,after,STATES[phase])
        for path,fd,ident in held:
            need(identity(os.fstat(fd))==identity(path.lstat())==ident and path.resolve(strict=True)==path,'all_backups_still_stable')
        need(identity(ROOT.lstat())[:5]==tuple(int(x) for x in root_identity),'root_still_bound')
        report.update(ok=True,phase=phase,originalCaptureAuthoritiesAndFdClosuresVerified=True,**result)
    except BaseException as error:
        report['errorType']=type(error).__name__
        if type(error) is RuntimeError: report['errorCode']=str(error)
        if isinstance(error,OSError): report['errno']=error.errno
    finally:
        signal.alarm(0)
        attempts=0; closed=0; close_errors=[]
        for _,fd,_ in held:
            attempts+=1
            try: os.close(fd); closed+=1
            except BaseException as error:
                row={'errorType':type(error).__name__}
                if isinstance(error,OSError): row['errno']=error.errno
                close_errors.append(row)
        report['fdCloseFacts']={'opened':len(held),'attemptedOnce':attempts,'knownClosed':closed,
                               'firstError':close_errors[0] if close_errors else None,'errorCount':len(close_errors)}
        if close_errors or closed!=len(held):
            report['ok']=False; report.setdefault('errorCode','one_or_more_backup_fd_closes_failed')
        print(json.dumps(report,sort_keys=True,separators=(',',':')))
    return 0 if report['ok'] else 1


if __name__=='__main__': raise SystemExit(main())
