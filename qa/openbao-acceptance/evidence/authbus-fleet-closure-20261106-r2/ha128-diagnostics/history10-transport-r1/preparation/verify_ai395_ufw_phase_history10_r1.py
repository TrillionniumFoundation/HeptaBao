def need(value,code):
    if not value: raise RuntimeError(code)


def identity(st):
    return tuple(getattr(st,k) for k in ('st_dev','st_ino','st_uid','st_gid','st_mode','st_nlink','st_size','st_mtime_ns','st_ctime_ns'))


def address(value):
    if isinstance(value,dict):
        need(set(value)=={'prefix'} and set(value['prefix'])=={'addr','len'},'exact_prefix')
        value=str(value['prefix']['addr'])+'/'+str(value['prefix']['len'])
    return str(ipaddress.ip_network(value,strict=False))


def core_iptables(tokens):
    if tokens[:2]!=['-A','ufw-user-input']: return None
    tail=tokens[2:]
    if len(tail)%2: return None
    pairs={}
    for key,value in zip(tail[::2],tail[1::2]):
        if key in pairs: return None
        pairs[key]=value
    allowed={'-s','-d','-i','-p','-m','--dport','--dports','-j'}
    if set(pairs)-allowed or pairs.get('-i')!='br0' or pairs.get('-p')!='tcp': return None
    try:
        source=address(pairs.get('-s','0.0.0.0/0'))
        destination=address(pairs.get('-d','0.0.0.0/0'))
    except ValueError: return None
    peer=next((x for x in TAGS if source==x+'/32'),None)
    if peer is None or destination!='192.168.0.11/32': return None
    if pairs.get('--dports')=='31040:31041':
        if pairs.get('-m')!='multiport' or '--dport' in pairs: return None
    elif pairs.get('--dport')=='31040:31041':
        if pairs.get('-m') not in (None,'tcp') or '--dports' in pairs: return None
    else: return None
    return peer,pairs.get('-j')


def iptables_semantics(raw,expected):
    output=[]; found={}; user_count=0
    for line in raw.decode().splitlines():
        if line.startswith('# Generated by iptables-save') or line.startswith('# Completed on'): continue
        line=re.sub(r'^\[\d+:\d+\]\s+','',line)
        if line.startswith(':'): line=re.sub(r'\[\d+:\d+\]$','[0:0]',line)
        if not line.strip(): continue
        tokens=shlex.split(line)
        ordinal=None
        if tokens[:2]==['-A','ufw-user-input']:
            ordinal=user_count; user_count+=1
        core=core_iptables(tokens)
        if core:
            peer,action=core
            need(peer in expected and peer not in found and action=='ACCEPT','exact_unique_live_owned_flow')
            found[peer]=ordinal
        else: output.append(tokens)
    need(set(found)==set(expected),'complete_live_owned_flow_set')
    return output,found,user_count


def persistent_semantics(raw,expected):
    lines=[line.strip() for line in raw.decode().splitlines() if line.strip()]
    output=[]; found=[]; index=0
    while index<len(lines):
        line=lines[index]
        if line.startswith('### tuple ### '):
            tokens=line.split(); fields=tokens[3:]
            tag_fields=[x[8:] for x in fields if x.startswith('comment=')]
            decoded=None
            if tag_fields:
                need(len(tag_fields)==1,'unique_tuple_comment')
                decoded=bytes.fromhex(tag_fields[0]).decode()
            own_peer=next((p for p,t in TAGS.items() if decoded==t),None)
            core_peer=None
            if len(fields)>=7 and fields[1]=='tcp' and fields[2]=='31040:31041':
                try:
                    if address(fields[3])=='192.168.0.11/32' and fields[4]=='any' and fields[6]=='in_br0':
                        core_peer=next((p for p in TAGS if address(fields[5])==p+'/32'),None)
                except ValueError: pass
            if own_peer is not None or core_peer is not None:
                need(own_peer==core_peer and own_peer in expected and own_peer not in found
                     and len(fields)==8 and fields[0]=='allow', 'exact_unique_persistent_owned_tuple')
                need(index+1<len(lines),'owned_tuple_body_present')
                body=shlex.split(lines[index+1]); core=core_iptables(body)
                need(core==(own_peer,'ACCEPT'),'owned_tuple_exact_generated_body')
                need(index+2==len(lines) or lines[index+2].startswith('###'), 'single_owned_tuple_body')
                found.append(own_peer)
                need(found==list(expected[:len(found)]),'persistent_owned_tuple_append_order')
                if len(found)==len(expected):
                    need(index+2<len(lines) and lines[index+2]=='### END RULES ###',
                         'last_owned_tuple_immediately_before_end_rules')
                index+=2; continue
            need(not found,'no_original_tuple_after_owned_append')
        output.append(shlex.split(line) if line.startswith('-A ') else line)
        index+=1
    need(found==list(expected),'complete_persistent_owned_tuple_set_and_order')
    return output


def nft_counter_normalize(value):
    if isinstance(value,list): return [nft_counter_normalize(x) for x in value]
    if not isinstance(value,dict): return value
    if set(value)=={'counter'} and isinstance(value['counter'],dict) and set(value['counter'])=={'packets','bytes'}:
        need(all(type(x) is int and x>=0 for x in value['counter'].values()),'valid_dynamic_counter')
        return {'counter':{'packets':0,'bytes':0}}
    return {k:nft_counter_normalize(v) for k,v in value.items()}


def exact_nft_owned(rule,peer):
    need(set(rule)=={'family','table','chain','handle','expr'},'owned_nft_rule_schema')
    need(isinstance(rule['expr'],list) and rule['expr'] and rule['expr'][-1]=={'accept':None},
         'owned_accept_must_follow_all_selectors')
    selectors={}; opaque=0; counters=0; accepts=0; protocol=None
    for expr in rule['expr']:
        need(isinstance(expr,dict) and len(expr)==1,'exact_nft_expression')
        if 'counter' in expr:
            need(set(expr['counter'])=={'packets','bytes'} and
                 all(type(x) is int and x>=0 for x in expr['counter'].values()),'exact_owned_counter')
            counters+=1; continue
        if 'accept' in expr:
            need(expr['accept'] is None,'exact_accept'); accepts+=1; continue
        if 'xt' in expr:
            need(expr['xt']=={'type':'match','name':'multiport'},'only_paired_opaque_multiport'); opaque+=1; continue
        need(set(expr)=={'match'},'unknown_owned_nft_expression')
        match=expr['match']; need(set(match)=={'op','left','right'} and match['op']=='==','exact_owned_match')
        left,right=match['left'],match['right']; key=None
        if left=={'meta':{'key':'iifname'}}: key='interface'; value=right
        elif left in ({'meta':{'key':'l4proto'}},{'payload':{'protocol':'ip','field':'protocol'}}):
            need(protocol is None and right=='tcp','exact_owned_tcp_protocol'); protocol='tcp'; continue
        elif left=={'payload':{'protocol':'ip','field':'saddr'}}: key='source'; value=address(right)
        elif left=={'payload':{'protocol':'ip','field':'daddr'}}: key='destination'; value=address(right)
        elif left=={'payload':{'protocol':'tcp','field':'dport'}}:
            need(right=={'range':[31040,31041]},'exact_owned_port_range'); key='portRange'; value=[31040,31041]
            protocol='tcp'
        else: raise RuntimeError('unknown_owned_nft_selector')
        need(key not in selectors,'unique_owned_nft_selector'); selectors[key]=value
    base={'interface':'br0','source':peer+'/32','destination':'192.168.0.11/32'}
    need(protocol=='tcp' and accepts==1 and counters==1,'exact_owned_nft_terminal')
    need((opaque==1 and selectors==base) or (opaque==0 and selectors=={**base,'portRange':[31040,31041]}),
         'complete_owned_nft_or_paired_opaque_shape')
    return opaque==1


def nft_semantics(raw,owned_ordinals,user_count,ipv6):
    parsed=json.loads(raw); need(set(parsed)=={'nftables'},'nft_top_schema')
    sequence=[]; index=0; matched=[]; opaque=0; chain_names=set()
    ordinals={ordinal:peer for peer,ordinal in owned_ordinals.items()}
    need(len(ordinals)==len(owned_ordinals),'unique_owned_ordinals')
    for entry in parsed['nftables']:
        need(isinstance(entry,dict) and len(entry)==1,'nft_entry_schema')
        kind,original=next(iter(entry.items())); data=dict(original)
        if kind=='rule':
            key=('rule',data.get('family'),data.get('table'),data.get('chain'))
            if key==('rule','ip','filter','ufw-user-input'):
                ordinal=index; index+=1
                if ordinal in ordinals:
                    peer=ordinals[ordinal]; opaque+=int(exact_nft_owned(data,peer)); matched.append(peer); continue
        elif kind=='chain':
            chain_names.add((data.get('family'),data.get('table'),data.get('name')))
        if kind in ('table','chain','rule','set','map','element','counter','quota','flowtable'):
            data.pop('handle',None)
        data=nft_counter_normalize(data)
        sequence.append({kind:data})
    need(index==user_count and set(matched)==set(owned_ordinals),'nft_iptables_ordered_chain_binding')
    for family,prefix in [('ip','ufw')]+([('ip6','ufw6')] if ipv6 else []):
        for suffix in ('input','output','forward','limit','limit-accept'):
            need((family,'filter',prefix+'-user-'+suffix) in chain_names,'existing_ufw_user_chain_complete')
    # Preserve the complete entry sequence, including table/chain enumeration and duplicates.
    return sequence,opaque


def compare(before,current,expected):
    for name in FILES-{'etc-ufw-user.rules','nft.original.private.log','iptables-filter.original.private.log'}:
        need(current[name]==before[name],'other_persistent_file_changed')
    need(persistent_semantics(before['etc-ufw-user.rules'],())==persistent_semantics(current['etc-ufw-user.rules'],expected),
         'all_other_persistent_semantics_unchanged')
    left,_,left_count=iptables_semantics(before['iptables-filter.original.private.log'],())
    right,ordinals,right_count=iptables_semantics(current['iptables-filter.original.private.log'],expected)
    need(left==right,'all_other_iptables_semantics_unchanged')
    need(right_count==left_count+len(expected) and
         all(ordinals[peer]==left_count+index for index,peer in enumerate(expected)),
         'owned_live_rules_appended_in_approved_order')
    flags=re.findall(rb'(?m)^IPV6=(yes|no)\s*$',before['etc-default-ufw'])
    need(len(flags)==1,'explicit_ipv6_configuration'); ipv6=flags[0]==b'yes'
    left,_=nft_semantics(before['nft.original.private.log'],{},left_count,ipv6)
    right,opaque=nft_semantics(current['nft.original.private.log'],ordinals,right_count,ipv6)
    need(left==right,'all_other_nft_manager_semantics_unchanged')
    return {'allOtherPersistentAndKernelSemanticsUnchanged':True,'ownedPeerFlows':list(expected),
            'ownedRulesPerView':len(expected),'opaqueMultiportRulesBoundToFullIptablesSameOrdinal':opaque,
            'countersAndNftHandlesExcludedOnlyAsDeclared':True,'existingUfwUserChainsComplete':True}


